"""Section 4: turn a schedule into synth_core.v (datapath + FSM).

Input: the result of scheduler.schedule(); every op has a cycle and a unit.
Output: one Verilog module, synth_core. Its ports never change, so top.v
does not need to change when the equations do.

Inputs are entered one at a time, like the CLI's "inputs" command shows:
in_sel (SW13-SW8) picks input number i, in_val is its value, and an
in_write pulse stores it. This only works in the LOAD state.

FSM states: 0 = LOAD, 1..N = one state per cycle, N+1 = DONE.
In state c the muxes route the right registers into each unit; pressing
step writes the results and moves to state c+1 on the same clock edge.
"""

from synthesis.dag import is_number

UNIT_MODULE = {"add": "adder", "sub": "subtractor", "mul": "multiplier"}

TOP = """
module synth_core #(parameter W = {width}) (
    input  wire         clk,
    input  wire         rst,
    input  wire         step,      // one-cycle pulse: go to the next state
    input  wire [5:0]   in_sel,    // which input to set (SW13-SW8)
    input  wire [7:0]   in_val,    // value for that input
    input  wire         in_write,  // one-cycle pulse: store in_val (LOAD state only)
    input  wire [4:0]   fu_sel,    // which value disp_val shows
    output reg  [W-1:0] disp_val,
    output wire [4:0]   state,     // 0 = LOAD, 1..{last} = cycles, {done} = DONE
    output wire         done
);
    // ---------------- FSM: state register ----------------
    reg [4:0] st;
    assign state = st;
    assign done  = (st == {done});

    always @(posedge clk) begin
        if (rst)
            st <= 0;
        else if (step && !done)
            st <= st + 1;
    end
"""


def reg(name):
    """Register for a variable (X -> r_X). Constants such as 3 stay as they are."""
    if is_number(name):
        return name
    return "r_" + name


def unit_list(result):
    """add0, add1, ..., sub0, ..., mul0, ..."""
    units = []
    for t in ("add", "sub", "mul"):
        for k in range(result["units"][t]):
            units.append(t + str(k))
    return units


def view_list(result):
    """What fu_sel = 0, 1, 2, ... shows: unit outputs, results, inputs (max 32)."""
    view = []
    for unit in unit_list(result):
        view.append((unit, unit + "_y"))
    for op in result["ops"]:
        view.append((op["dest"], reg(op["dest"])))
    for var in result["inputs"]:
        view.append((var, reg(var)))
    return view[:32]


def generate_verilog(result, width=16):
    ops = sorted(result["ops"], key=lambda op: op["cycle"])
    inputs = result["inputs"]
    done = result["num_cycles"] + 1
    if done > 31:
        raise ValueError(f"{result['num_cycles']} cycles do not fit in a 5-bit state")
    if len(inputs) > 64:
        raise ValueError(f"{len(inputs)} inputs do not fit in a 6-bit in_sel")
    view = view_list(result)

    # Header: what in_sel and fu_sel mean, for the demo
    v = ["// Generated by synthesis/codegen.py - do not edit by hand."]
    for i in range(len(inputs)):
        v.append(f"// in_sel {i:>2} sets {inputs[i]}")
    for i in range(len(view)):
        v.append(f"// fu_sel {i:>2} shows {view[i][0]}")
    v.append(TOP.format(width=width, last=done - 1, done=done))

    # 1. One register per variable
    names = [reg(var) for var in inputs] + [reg(op["dest"]) for op in ops]
    v.append("    // ---------------- Registers: one per variable ----------------")
    v.append(f"    reg [W-1:0] {', '.join(names)};")
    v.append("")

    # 2. FSM outputs: each result is written in the state of its cycle
    v.append("    // ---------------- FSM outputs: write enables ----------------")
    v.append("    wire load = (st == 0);")
    for op in ops:
        v.append(f"    wire en_{op['dest']} = (st == {op['cycle']});")
    v.append("")

    # 3. Muxes and units. A port that reads more than one register gets a
    #    select signal (decoded from the FSM state) and a mux.
    v.append("    // ---------------- Datapath: muxes and functional units ----------------")
    for unit in unit_list(result):
        for port in ("a", "b"):
            sources = []        # different registers this port reads
            select = ""         # which source to pick in which state
            for op in ops:
                if op["unit"] != unit:
                    continue
                src = reg(op[port])
                if src not in sources:
                    sources.append(src)
                select += f"(st == {op['cycle']}) ? {sources.index(src)} : "

            if len(sources) == 1:
                v.append(f"    wire [W-1:0] {unit}_{port} = {sources[0]};")
            else:
                mux = ""
                for k in range(len(sources) - 1):
                    mux += f"({unit}_sel_{port} == {k}) ? {sources[k]} : "
                v.append(f"    wire [4:0]   {unit}_sel_{port} = {select}0;")
                v.append(f"    wire [W-1:0] {unit}_{port} = {mux}{sources[-1]};")
        v.append(f"    wire [W-1:0] {unit}_y;")
        v.append(f"    {UNIT_MODULE[unit[:3]]} #(.W(W)) u_{unit} "
                 f"(.a({unit}_a), .b({unit}_b), .y({unit}_y));")
        v.append("")

    # 4. Register writes: inputs with in_write (LOAD only), results with step
    v.append("    // ---------------- Register writes ----------------")
    v.append("    always @(posedge clk) begin")
    v.append("        if (rst) begin")
    for name in names:
        v.append(f"            {name} <= 0;")
    v.append("        end else begin")
    v.append("            if (in_write && load) begin")
    v.append("                case (in_sel)")
    for i in range(len(inputs)):
        v.append(f"                    {i}: {reg(inputs[i])} <= in_val;")
    v.append("                    default: ;")
    v.append("                endcase")
    v.append("            end")
    v.append("            if (step) begin")
    for op in ops:
        v.append(f"                if (en_{op['dest']}) {reg(op['dest'])} <= {op['unit']}_y;")
    v.append("            end")
    v.append("        end")
    v.append("    end")
    v.append("")

    # 5. Observability: fu_sel picks what goes to the display
    v.append("    // ---------------- fu_sel picks what disp_val shows ----------------")
    v.append("    always @(*) begin")
    v.append("        case (fu_sel)")
    for i in range(len(view)):
        v.append(f"            {i}: disp_val = {view[i][1]};")
    v.append("            default: disp_val = 0;")
    v.append("        endcase")
    v.append("    end")
    v.append("endmodule")
    return "\n".join(v) + "\n"


def write_verilog(result, path, width=16):
    with open(path, "w") as f:
        f.write(generate_verilog(result, width))
